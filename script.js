const KEY = "islamLearningTodoV1";
const saved = JSON.parse(localStorage.getItem(KEY) || "{}");

const roadmapEl = document.getElementById("roadmap");
const stageCountEl = document.getElementById("stageCount");
const lessonCountEl = document.getElementById("lessonCount");
const doneCountEl = document.getElementById("doneCount");
const progressTextEl = document.getElementById("progressText");
const progressLabelEl = document.getElementById("progressLabel");
const progressFillEl = document.getElementById("progressFill");
const resetBtn = document.getElementById("resetBtn");

function isDone(stageIndex, lessonIndex) {
  return saved[`${stageIndex}-${lessonIndex}`] === true;
}

function render() {
  roadmapEl.innerHTML = "";

  roadmap.forEach((stage, stageIndex) => {
    const stageDone = stage.lessons.filter((_, lessonIndex) =>
      isDone(stageIndex, lessonIndex)
    ).length;

    const stageEl = document.createElement("section");
    stageEl.className = "stage";
    if (stageIndex === 0) stageEl.classList.add("open");

    stageEl.innerHTML = `
      <div class="stage-header">
        <div class="stage-title">
          <div class="stage-number">${stageIndex + 1}</div>
          <div>
            <h2>${stage.title}</h2>
            <p class="stage-desc">${stage.desc}</p>
          </div>
        </div>
        <div style="display:flex;align-items:center;gap:14px;">
          <span class="stage-progress">${stageDone}/${stage.lessons.length}</span>
          <span class="chevron">⌄</span>
        </div>
      </div>
      <div class="stage-body">
        <div class="lessons">
          ${stage.lessons.map(([title, desc], lessonIndex) => `
            <label class="lesson ${isDone(stageIndex, lessonIndex) ? "done" : ""}">
              <input
                type="checkbox"
                data-stage="${stageIndex}"
                data-lesson="${lessonIndex}"
                ${isDone(stageIndex, lessonIndex) ? "checked" : ""}
              />
              <div>
                <p class="lesson-title">${title}</p>
                <p class="lesson-desc">${desc}</p>
              </div>
              <span class="lesson-tag">درس</span>
            </label>
          `).join("")}
        </div>
      </div>
    `;

    stageEl.querySelector(".stage-header").addEventListener("click", () => {
      stageEl.classList.toggle("open");
    });

    stageEl.querySelectorAll("input[type=checkbox]").forEach(input => {
      input.addEventListener("change", (e) => {
        const stageIndex = e.target.dataset.stage;
        const lessonIndex = e.target.dataset.lesson;
        saved[`${stageIndex}-${lessonIndex}`] = e.target.checked;
        localStorage.setItem(KEY, JSON.stringify(saved));
        render();
      });
    });

    roadmapEl.appendChild(stageEl);
  });

  updateStats();
}

function updateStats() {
  const totalLessons = roadmap.reduce((sum, stage) => sum + stage.lessons.length, 0);
  const doneLessons = Object.values(saved).filter(Boolean).length;
  const progress = totalLessons ? Math.round((doneLessons / totalLessons) * 100) : 0;

  stageCountEl.textContent = roadmap.length;
  lessonCountEl.textContent = totalLessons;
  doneCountEl.textContent = doneLessons;
  progressTextEl.textContent = `${progress}%`;
  progressLabelEl.textContent = `${doneLessons} / ${totalLessons}`;
  progressFillEl.style.width = `${progress}%`;
}

resetBtn.addEventListener("click", () => {
  const ok = confirm("متأكد إنك عايز تمسح كل تقدمك؟");
  if (!ok) return;

  localStorage.removeItem(KEY);
  Object.keys(saved).forEach(key => delete saved[key]);
  render();
});

render();
